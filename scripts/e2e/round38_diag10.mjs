import { chromium } from 'playwright'
import fs from 'fs'
const DOC = JSON.parse(fs.readFileSync('/home/z/my-project/samoffice/scripts/fixtures/comments_doc.udm.json', 'utf-8'))
const b = await chromium.launch({ args: ['--no-sandbox'] })
const p = await (await b.newContext({ viewport: { width: 1400, height: 900 } })).newPage()
await p.goto('http://localhost:18400/?r38j=' + Date.now(), { waitUntil: 'networkidle' })
await p.waitForTimeout(1200)
await p.evaluate(d => window.__setDocForTest(d), DOC)
await p.waitForTimeout(2500)
const n0 = await p.evaluate(() => window.__r38LayoutLog.length)
await p.click('.ProseMirror', { position: { x: 300, y: 80 }, force: true, timeout: 8000 })
await p.waitForTimeout(200)
for (let i = 0; i < 30; i++) await p.keyboard.press('Enter')
await p.waitForTimeout(2500)
const n1 = await p.evaluate(() => window.__r38LayoutLog.length)
const log = await p.evaluate(() => window.__r38LayoutLog.slice(n0_len = 0))
// 取 Enter 后的日志：全局计数差
const logAll = await p.evaluate(() => window.__r38LayoutLog)
const after = logAll.slice(n0)
const lastFew = after.slice(-6).map(e => ({ c1: Math.round(e.c1mark || -1), pane: Math.round(e.paneTop || -1), n: e.n }))
const live = await p.evaluate(() => Math.round(document.querySelector('.comment-mark[data-comment-id="c1"]').getBoundingClientRect().top))
const styleTop = await p.evaluate(() => document.getElementById('comment-card-c1').style.top)
console.log('Enter 前日志数:', n0, '后新增:', n1 - n0)
console.log('Enter 后末 6 次布局读数:', JSON.stringify(lastFew))
console.log('页面实时 c1markTop:', live, '| styleTop:', styleTop)
await b.close()
