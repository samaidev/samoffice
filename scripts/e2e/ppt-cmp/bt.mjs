import { chromium } from 'playwright'
const b = await chromium.launch({ args: ['--no-sandbox'] })
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage()
await p.goto('http://localhost:18400', { waitUntil: 'networkidle' })
await p.waitForTimeout(800)
await p.evaluate(() => { localStorage.setItem('samoffice_lang', 'zh') })
await p.reload({ waitUntil: 'networkidle' }); await p.waitForTimeout(1000)
await p.locator('[data-testid="menu-files"]').click({ force: true }); await p.waitForTimeout(400)
const [ch] = await Promise.all([p.waitForEvent('filechooser', { timeout: 10000 }), (async () => { await p.locator('text=📂').first().click({ force: true }) })()])
await ch.setFiles('/home/z/my-project/upload/装备工业的互联网 机遇.pptx')
await p.waitForTimeout(4000)
await p.evaluate(() => { const l = document.querySelector('.w-40, .w-48'); l?.querySelectorAll('.space-y-2 > div')[8]?.dispatchEvent(new MouseEvent('click', { bubbles: true })) })
await p.waitForTimeout(800)
const r = await p.evaluate(() => {
  const dots = Array.from(document.querySelectorAll('.slide-canvas span')).filter(x => (x.textContent || '') === '•')
  return dots.slice(0, 3).map(d => ({ color: d.style.color, inline: d.getAttribute('style')?.slice(0, 80) }))
})
console.log(JSON.stringify(r))
await b.close()
