def gen_zuci(rng):
    ch, words = rng.choice(list(WORD_GROUPS.items()))
    return "chinese", f"组词练习：用「{ch}」字组词：{('、'.join(words))}。"


def gen_antonym(rng):
    a, b = rng.choice(ANTONYMS)
    objs = ["箱子", "盒子", "树", "房子", "绳子", "路", "衣服", "石头"]
    o1, o2 = rng.sample(objs, 2)
    return "chinese", f"反义词：「{a}」的反义词是「{b}」。例句：这个{o1}很{a}，那个{o2}很{b}。"


def gen_zaoju(rng):
    word = rng.choice(SENT_WORDS)
    return "chinese", f"造句练习：用「{word}」造句。\n例句：{SENT_EXAMPLES[word]}"


def gen_season_essay(rng):
    s, variants = rng.choice(list(SEASONS.items()))
    scene, animal, feel = rng.choice(variants)
    return "chinese", (f"短文：《{s}来了》\n{s}来了！{scene}。{animal}。"
                       f"{s}的天气很{feel}，我爱{s}。")


def gen_nature(rng):
    q, a = rng.choice(NATURE_QA)
    return "nature", f"问：{q}\n答：{a}"


GENS = [(2, gen_zuci), (2, gen_antonym), (2, gen_zaoju), (2, gen_season_essay), (3, gen_nature)]


def main():
    args = make_argparser("Stage1 小学语文/自然数据生成").parse_args()
    rng = random.Random(args.seed)
    w = JsonlWriter(args.outdir, "stage1_chinese.jsonl", max_unique=args.max_unique)
    fns, weights = [g for _, g in GENS], [wt for wt, _ in GENS]
    for _ in range(args.num):
        subject, text = rng.choices(fns, weights=weights)[0](rng)
        r = w.write("s1-chn", 1, subject, "小学", text)
        if r == "STOP":
            break
    w.close()


if __name__ == "__main__":
    main()
