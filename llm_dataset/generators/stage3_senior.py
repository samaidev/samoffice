MOLS = [("H2O", "水", 18), ("CO2", "二氧化碳", 44), ("NaOH", "氢氧化钠", 40),
        ("H2SO4", "硫酸", 98), ("NaCl", "氯化钠", 58.5), ("CaCO3", "碳酸钙", 100),
        ("O2", "氧气", 32), ("HCl", "氯化氢", 36.5), ("NH3", "氨气", 17), ("CH4", "甲烷", 16),
        ("C2H5OH", "乙醇", 46), ("Fe2O3", "氧化铁", 160), ("CuSO4", "硫酸铜", 159.5),
        ("KCl", "氯化钾", 74.5), ("MgO", "氧化镁", 40.5)]

def mole_calc(rng):
    f, name, M = rng.choice(MOLS)
    n = rng.choice([0.2, 0.25, 0.4, 0.5, 0.75, 1, 1.25, 1.5, 2, 2.5, 3, 4, 5, 6])
    m = n * M
    m = int(m) if m == int(m) else round(m, 2)
    return "chemistry", (f"题目：{n} mol {name}（{f}）的质量是多少？（M = {M} g/mol）\n"
                         f"解：m = nM = {n}×{M} = {m} g。\n答：{m} 克。")

def concentration(rng):
    n, V = rng.choice([0.2, 0.25, 0.5, 0.75, 1, 1.25, 1.5, 2, 3, 4]), rng.choice([0.2, 0.25, 0.5, 0.75, 1, 1.5, 2, 4])
    c = n / V
    c = int(c) if c == int(c) else round(c, 3)
    return "chemistry", (f"题目：{n} mol 溶质配成 {V} L 溶液，求物质的量浓度。\n"
                         f"解：c = n/V = {n}÷{V} = {c} mol/L。\n答：{c} mol/L。")

def molar_vol(rng):
    Vm = rng.choice([22.4, 24.5])
    n = rng.choice([0.5, 1, 1.5, 2, 3])
    V = n * Vm
    return "chemistry", (f"题目：标准状况下（Vm = {Vm} L/mol）{n} mol 某气体体积约为多少？\n"
                         f"解：V = n·Vm = {n}×{Vm} = {V} L。\n答：{V} 升。")

def electric_circuit(rng):
    U, R = rng.choice([3, 6, 9, 12, 15]), rng.choice([2, 3, 4, 5, 6, 10, 12])
    I = U / R
    I = int(I) if I == int(I) else round(I, 3)
    P = round(U * I, 2)
    return "physics", (f"题目：电阻 {R} Ω 两端加 {U} V 电压，求电流和电功率。\n"
                       f"解：I = U/R = {U}/{R} = {I} A；P = UI = {U}×{I} = {P} W。\n答：电流 {I} A，功率 {P} W。")

def heat_calc(rng):
    c, m, dt = rng.choice([0.39, 0.46, 0.9, 4.2]), rng.randint(1, 20), rng.randint(5, 80)
    Q = round(c * m * dt, 2)
    return "physics", (f"题目：质量 {m} kg 物质比热容 {c} kJ/(kg·℃)，升温 {dt}℃，吸热量？\n"
                       f"解：Q = cmΔt = {c}×{m}×{dt} = {Q} kJ。\n答：{Q} 千焦。")

