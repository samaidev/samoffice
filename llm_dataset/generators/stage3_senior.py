QA_BANKS = [("biology", BIO_QA), ("geography", GEO_QA), ("politics", POL_QA)]
# 题干改写模板，制造变体
Q_REPHRASE = [
    lambda q: q,
    lambda q: "请回答：" + q,
    lambda q: q.rstrip("？?") + "，请简要说明。",
    lambda q: "【思考题】" + q,
    lambda q: "试述：" + q.rstrip("？?") + "。",
    lambda q: q.rstrip("？?") + "（请用自己的话概括）。",
]

def qa(subject, bank):
    def _f(rng):
        q, a = rng.choice(bank)
        q2 = rng.choice(Q_REPHRASE)(q)
        return subject, f"问：{q2}\n答：{a}"
    return _f

GENS = [
    (2, quad_vertex), (2, arith_seq), (2, geom_seq), (1, logarithm), (2, trig), (2, poly_derivative),
    (2, kinematics), (2, kinetic_energy), (1, free_fall), (2, work_energy), (1, pressure_calc),
    (1, buoyance),     (2, mole_calc), (1, concentration), (1, molar_vol), (1, electric_circuit), (1, heat_calc),
] + [(2, qa(s, b)) for s, b in QA_BANKS]

def main():
    args = make_argparser("Stage3 高中数据生成（高多样性）").parse_args()
    rng = random.Random(args.seed)
    w = JsonlWriter(args.outdir, "stage3_senior.jsonl", max_unique=args.max_unique)
    fns, weights = [g for _, g in GENS], [wt for wt, _ in GENS]
    for _ in range(args.num):
        subject, text = rng.choices(fns, weights=weights)[0](rng)
        r = w.write("s3-snr", 3, subject, "高中", text)
        if r == "STOP":
            break
    w.close()

if __name__ == "__main__":
    main()
