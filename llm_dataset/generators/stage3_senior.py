def kinematics(rng):
    v0, a, t = rng.randint(0, 25), rng.randint(1, 12), rng.randint(2, 18)
    v = v0 + a * t
    s = v0 * t + a * t * t / 2
    s = int(s) if s == int(s) else round(s, 2)
    return "physics", (f"题目：物体初速度 {v0} m/s 匀加速运动，a = {a} m/s²，求 {t} s 末速度和位移。\n"
                       f"解：v = v₀+at = {v0}+{a}×{t} = {v} m/s；s = v₀t+½at² = {v0}×{t}+½×{a}×{t}² = {s} m。\n"
                       f"答：速度 {v} m/s，位移 {s} m。")

def kinetic_energy(rng):
    m, v = rng.randint(1, 80), rng.choice([2, 4, 6, 8, 10, 12, 14, 16, 20])
    return "physics", (f"题目：质量 {m} kg 物体以 {v} m/s 运动，求动能。\n"
                       f"解：Ek = ½mv² = ½×{m}×{v}² = {m * v * v // 2} J。\n答：{m * v * v // 2} 焦耳。")

def free_fall(rng):
    t, g = rng.randint(1, 12), 10
    return "physics", (f"题目：物体自由下落 {t} s（g = {g} m/s²），求高度和末速度。\n"
                       f"解：h = ½gt² = ½×{g}×{t}² = {g * t * t // 2} m；v = gt = {g * t} m/s。\n"
                       f"答：高度 {g * t * t // 2} m，末速度 {g * t} m/s。")

def work_energy(rng):
    F, s, theta = rng.randint(5, 100), rng.randint(2, 50), rng.choice([0, 30, 45, 60, 90])
    import math as _m
    c = round(_m.cos(_m.radians(theta)), 3)
    if theta == 90:
        W = 0
    else:
        W = int(F * s * _m.cos(_m.radians(theta))) if (F * s * _m.cos(_m.radians(theta))) == int(F * s * _m.cos(_m.radians(theta))) else round(F * s * _m.cos(_m.radians(theta)), 2)
    return "physics", (f"题目：水平力 {F} N 沿与位移成 {theta}° 方向推物体前进 {s} m，求做功。\n"
                       f"解：W = Fscosθ = {F}×{s}×cos{theta}° = {F}×{s}×{c} = {W} J。\n答：{W} 焦耳。")

def pressure_calc(rng):
    F, S = rng.randint(10, 500), rng.choice([0.5, 1, 2, 4, 5, 10, 20])
    p = round(F / S, 2)
    return "physics", (f"题目：{F} N 的压力作用在 {S} m² 面积上，求压强。\n"
                       f"解：p = F/S = {F}÷{S} = {p} Pa。\n答：{p} 帕斯卡。")

def buoyance(rng):
    rho, V = rng.choice([0.8, 1.0, 1.03, 7.9, 11.3]), rng.choice([0.001, 0.002, 0.005, 0.01, 0.02])
    Fb = round(rho * 1000 * 10 * V, 4)
    return "physics", (f"题目：体积 {V} m³ 的物块浸没在密度 {rho}×10³ kg/m³ 液体中，求浮力（g=10）。\n"
                       f"解：F浮 = ρ液gV排 = {rho}×10³×10×{V} = {Fb} N。\n答：{Fb} 牛。")

