def quad_vertex(rng):
    a = rng.choice([1, 2, 3, 4, 5, -1, -2, -3])
    h, k = rng.randint(-9, 9), rng.randint(-12, 12)
    kind = "最小值" if a > 0 else "最大值"
    b, c = -2 * a * h, a * h * h + k
    return "math", (f"题目：求二次函数 y = {a}x²{b:+d}x{c:+d} 的顶点坐标与{kind}。\n"
                    f"解：配方得 y = {a}(x{-h:+d})²{k:+d}，顶点 ({h}, {k})；"
                    f"a = {a}，开口向{'上' if a > 0 else '下'}，在 x = {h} 处取{kind} {k}。\n"
                    f"答：顶点 ({h}, {k})，{kind} {k}。")

def arith_seq(rng):
    a1, d, n = rng.randint(1, 30), rng.randint(2, 15), rng.randint(5, 30)
    an = a1 + (n - 1) * d
    sn = n * (a1 + an) // 2
    return "math", (f"题目：等差数列 a₁ = {a1}，d = {d}，求 a{n} 与 S{n}。\n"
                    f"解：a{n} = a₁+(n-1)d = {a1}+{n-1}×{d} = {an}；S{n} = n(a₁+a{n})/2 = {n}×{a1 + an}/2 = {sn}。\n"
                    f"答：a{n} = {an}，S{n} = {sn}。")

def geom_seq(rng):
    a1, q, n = rng.randint(1, 9), rng.choice([2, 3, 4]), rng.randint(3, 10)
    val = a1 * q ** (n - 1)
    return "math", (f"题目：等比数列 a₁ = {a1}，q = {q}，求第{n}项。\n"
                    f"解：a{n} = a₁·qⁿ⁻¹ = {a1}×{q}^{n-1} = {val}。\n答：a{n} = {val}。")

