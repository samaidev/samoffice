def gen_wiki(rng):
    name, cat, props, facts = rng.choice(SUBJECTS)
    # 随机选 2~3 条属性 + 1 条补充事实，顺序打乱 → 大量组合
    picks = rng.sample(props, k=min(len(props), rng.randint(2, 3)))
    fact = rng.choice(facts)
    body = "，".join(picks) + "，" + fact + "。"
    style = rng.randint(0, 3)
    if style == 0:
        return f"{name}（{cat}）：{body}"
    if style == 1:
        return f"【{cat}小百科】{name}。{body}"
    if style == 2:
        return f"问：请介绍一下{name}。\n答：{body}"
    return f"你知道吗？{name}是一种{cat}。{body}{rng.choice(ADVICE)}"


def gen_idiom(rng):
    w, meaning, story = rng.choice(IDIOMS)
    style = rng.randint(0, 3)
    if style == 0:
        return f"成语：{w}。释义：{meaning}。典故：{story}。"
    if style == 1:
        return f"问：「{w}」是什么意思？\n答：{meaning}。典故：{story}。"
    if style == 2:
        return f"{w}：{meaning}。它来源于一个故事——{story}"
    return f"学习成语「{w}」：{meaning}（故事：{story}）{rng.choice(ADVICE)}"


def gen_tip(rng):
    topic, scenes, benefits = rng.choice(TIP_TOPICS)
    scene = rng.choice(scenes)
    benefit = rng.choice(benefits)
    q = f"为什么{scene}要{topic}？"
    a = f"{scene}{topic}很重要：{benefit}。{rng.choice(ADVICE)}"
    return f"问：{q}\n答：{a}"


GENS = [(3, gen_wiki), (2, gen_idiom), (2, gen_tip)]


def main():
    args = make_argparser("通用语料生成（高多样性）").parse_args()
    rng = random.Random(args.seed)
    w = JsonlWriter(args.outdir, "general_corpus.jsonl", max_unique=args.max_unique)
    fns, weights = [g for _, g in GENS], [wt for wt, _ in GENS]
    for _ in range(args.num):
        text = rng.choices(fns, weights=weights)[0](rng)
        r = w.write("gen", 9, "general", "", text)
        if r == "STOP":
            break
    w.close()


if __name__ == "__main__":
    main()
